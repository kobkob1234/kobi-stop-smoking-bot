import { test } from 'node:test';
import assert from 'node:assert/strict';
import * as KB from '../src/kb.js';

// ניסוחים אמיתיים שנמדדו. לפני התיקונים 6 מהם החזירו אפס קטעים.
const shouldHit = [
  ['אני בטוח שאחת לא תזיק', 'רק אחת', 'הנושא המרכזי אצל קאר — החזיר אפס קטעים'],
  ['אחת קטנה לא נורא', 'רק אחת'],
  ['החברים שלי מעשנים ואני מרגיש מוזר לידם'],
  ['הוויפ היה החבר שלי האמת'],
  ['למה בכלל התחלתי עם זה'],
  ['אני מפחד שאחזור לזה בעוד חודש'],
  ['למה אני עדיין חושב על זה כל הזמן אחרי שלושה שבועות'],
  ['אני לא ישן טוב מאז שהפסקתי'],
  ['כמה זמן זה ייקח עד שזה יפסיק'],
  ['אני עצבני על כולם מאז שהפסקתי'],
  ['עליתי במשקל'],
  ['בת הזוג שלי אמרה שאני נסבל פחות'],
  ['מה עושים כששותים אלכוהול'],
  ['קשה לי בבקרים'],
  ['אני משועמם וזה כשזה הכי קשה'],
];

for (const [q, expectTopic, why] of shouldHit) {
  test(`שליפה: "${q}"${why ? ` (${why})` : ''}`, () => {
    const hits = KB.search(q, 3);
    assert.ok(hits.length > 0, 'לא נמצא שום קטע');
    if (expectTopic) {
      assert.ok(hits.some(h => h.t.includes(expectTopic)),
        `ציפיתי ל"${expectTopic}", קיבלתי: ${hits.map(h => h.t).join(' · ')}`);
    }
  });
}

test('באג הצירופים: מילת מפתח עם מילית קצרה עדיין נתפסת', () => {
  // "רק אחת" — כל מילות המפתח של הנושא הן צירופים, ותנאי kw.length>1
  // פסל אותם כשנשארה מילת תוכן אחת. לנושא לא הייתה שום דרך להיתפס.
  assert.ok(KB.search('שאחת לא תזיק לי', 2).some(h => h.t.includes('רק אחת')));
});

test('סף רלוונטיות: שיחת חולין לא מקבלת קטע', () => {
  for (const q of ['מה השעה', 'ספר לי בדיחה', 'תודה רבה לך', 'אני הולך לישון']) {
    assert.equal(KB.search(q, 3).length, 0, `"${q}" קיבל קטע`);
  }
});

test('כל התוצאות עוברות את סף הרלוונטיות', () => {
  for (const q of shouldHit.map(x => x[0])) {
    for (const h of KB.search(q, 3)) {
      assert.ok(h.score >= KB.MIN_SCORE, `"${q}" → ${h.t} בציון ${h.score}`);
    }
  }
});

test('התאמה חלשה מסומנת למודל ולא מוגשת כסמכות', () => {
  const ctx = KB.context('מה עושים כששותים אלכוהול', 3);
  assert.ok(ctx.length > 0);
  // כל קטע מתחת ל-STRONG_SCORE חייב לשאת אזהרה
  const weak = KB.search('מה עושים כששותים אלכוהול', 3).filter(h => h.score < KB.STRONG_SCORE);
  if (weak.length) assert.match(ctx, /התאמה חלשה/);
});

test('answer מחזיר null מתחת לסף, ולא ניחוש', () => {
  assert.equal(KB.answer('מה אתה חושב על הכדורגל'), null);
});

test('לכל נושא יש מקור מצוטט', () => {
  for (const e of KB.KB) {
    assert.ok(e.src && e.src.length > 3, `לנושא "${e.t}" אין מקור`);
    assert.ok(e.k && e.k.length > 0, `לנושא "${e.t}" אין מילות מפתח`);
  }
});

test('אין מזהי נושא כפולים', () => {
  const ids = KB.KB.map(e => e.id);
  assert.equal(new Set(ids).size, ids.length);
});
