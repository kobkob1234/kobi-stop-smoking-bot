import { test } from 'node:test';
import assert from 'node:assert/strict';
import { fastRoute } from '../src/index.js';

const cases = [
  // --- דרגה 3: הדחופה. חייבת לגבור על כל השאר ---
  ['אני בדרך לחנות', 'enroute', 'נתפס פעם כדחף רגיל — הניסוח הדחוף קיבל את התגובה הרפה'],
  ['אני בדרך לקנות', 'enroute'],
  ['אני עומד בקופה', 'enroute'],
  ['היד על הארנק', 'enroute'],
  ['הולך לקנות עכשיו', 'enroute'],

  // --- דרגה 2: תירוצים לצאת. חייבת לגבור על דחף רגיל ---
  ['נגמר החלב אני קופץ לסופר', 'planning'],
  ['אני מחפש תירוץ לצאת', 'planning'],
  ['משכנע את עצמי שזה בסדר', 'planning'],
  ['סתם אסתובב קצת', 'planning'],

  // --- דרגה 1: דחף רגיל ---
  ['בא לי נורא עכשיו', 'wave'],
  ['יש לי דחף עכשיו', 'wave'],
  ['מתחשק לי', 'wave'],
  ['לא מחזיק יותר', 'wave'],
  ['מגיע לי אחת', 'wave'],

  // --- עבר: חייב להקדים את זיהוי הדחף ---
  ['קניתי', 'slip', 'אחרת "קניתי" נתפס כ"רוצה לקנות"'],
  ['שאפתי אתמול', 'slip'],

  // --- שלילה: ניצחון, לא מעידה ולא דחף ---
  ['התגברתי, לא קניתי', 'win', 'סימון שגוי כמעידה מזין את גלאי ההסלמה בנתון כזב'],
  ['כמעט קניתי ולא', 'win'],
  ['לא בא לי בכלל היום', null],

  // --- שאר הכוונות ---
  ['יוצא מהבית', 'out'],
  ['לקחתי מסטיק', 'gum'],
  ['הדבקתי מדבקה', 'patch'],
  ['סטטוס', 'status'],

  // --- מה שחייב לעבור למודל ---
  ['מה שלומך', null],
  ['היה לי יום ארוך בעבודה', null],
  ['תודה', null],
];

for (const [input, expected, why] of cases) {
  test(`ניתוב: "${input}" → ${expected || 'למודל'}${why ? ` (${why})` : ''}`, () => {
    assert.equal(fastRoute(input), expected);
  });
}

test('גרשיים עבריים לא שוברים את ההתאמה', () => {
  assert.equal(fastRoute('אני ב״דרך לחנות״'.replace('״דרך', 'דרך')), 'enroute');
});

test('סדר הדרגות: enroute גובר על planning וגם על urge', () => {
  // משפט שמכיל סימנים לשלוש הדרגות — הדחופה חייבת לנצח
  assert.equal(fastRoute('בא לי, אני מחפש תירוץ, ואני כבר בדרך לקנות'), 'enroute');
});

test('סדר הדרגות: planning גובר על urge', () => {
  assert.equal(fastRoute('בא לי משהו, נגמר החלב אז אקפוץ לסופר'), 'planning');
});
