/**
 * ציטוט לרמת מצב רוח.
 *
 *  הרוטציה חייבת להיות **רציפה ולא מחזורית-ליום**: עם 3 בדיקות ביום,
 *  אינדקס שנגזר רק ממספר היום היה מחזיר את אותו ציטוט שלוש פעמים
 *  באותו ערב. `seq` הוא מונה רץ (יום × בדיקות + מספר הבדיקה), ולכן
 *  שתי תשובות עוקבות לעולם לא מקבלות את אותו ציטוט — גם באותה דרגה.
 *  חזרה מותרת אחרי מחזור מלא, אבל אף פעם ברצף.
 */
export function moodQuote(level, seq = 0) {
  const f = MOOD_FEEDBACK[Math.max(1, Math.min(5, level))];
  return f.quotes[Math.abs(seq) % f.quotes.length];
}
