// ---------- זמן ישראל (כולל שעון קיץ) ----------
export function il(now = new Date()) {
  const p = {};
  new Intl.DateTimeFormat('en-GB', {
    timeZone: TZ, year: 'numeric', month: '2-digit', day: '2-digit',
    hour: '2-digit', minute: '2-digit', hourCycle: 'h23', weekday: 'short',
  }).formatToParts(now).forEach(x => { p[x.type] = x.value; });

  const dow = DOW_EN.indexOf(p.weekday);
  return {
    iso: `${p.year}-${p.month}-${p.day}`,
    y: +p.year, mo: +p.month, d: +p.day,
    hour: +p.hour, min: +p.minute,
    minutes: (+p.hour) * 60 + (+p.minute),
    dow, dowHe: DOW_HE[dow < 0 ? 0 : dow],
    hhmm: `${p.hour}:${p.minute}`,
  };
}

// ---------- חשבון תאריכים ----------
const toUTC = iso => { const [y, m, d] = iso.split('-').map(Number); return Date.UTC(y, m - 1, d); };
export const diffDays = (a, b) => Math.round((toUTC(b) - toUTC(a)) / 86400000);
export function addDaysISO(iso, n) {
  const d = new Date(toUTC(iso) + n * 86400000);
  return `${d.getUTCFullYear()}-${String(d.getUTCMonth() + 1).padStart(2, '0')}-${String(d.getUTCDate()).padStart(2, '0')}`;
}
export function fmtHe(iso) { const [y, m, d] = iso.split('-'); return `${+d}.${+m}.${y.slice(2)}`; }
export const dayNum = iso => diffDays(QUIT, iso) + 1;   // 1 = יום ההפסקה

// ---------- התמונה של יום מסוים ----------
// siteOffset מיישר את הרוטציה למקום שבו הוא באמת הדביק — /מקום בצ׳אט.
export function planFor(iso, siteOffset = 0) {
  const n = dayNum(iso);
  if (n < 1) return { iso, n, before: true, daysToQuit: 1 - n };
  if (n > TOTAL_DAYS) return { iso, n, after: true, cleanDays: n - 1 };

  const i = n - 1;
  let acc = 0, ph = PHASES[PHASES.length - 1];
  for (const p of PHASES) { if (i < acc + p.days) { ph = p; break; } acc += p.days; }

  // מקום ההדבקה נמדד מהעוגן ולא ממספר היום בתוכנית, כדי שהוא יישאר
  // נכון גם אם התוכנית תזוז. siteOffset הוא תיקון ידני מעל העוגן.
  const L = SITES.length;
  const siteIndex = ((((SITE_ANCHOR.index + diffDays(SITE_ANCHOR.iso, iso) + siteOffset) % L) + L) % L);

  return {
    iso, n, i,
    week: Math.floor(i / 7) + 1,
    dose: ph.dose,
    phase: ph.label,
    phaseKey: ph.key,
    product: ph.product,
    site: SITES[siteIndex],
    siteIndex,
    clean: i,                                  // ימים נקיים שהושלמו
    focus: WEEK_FOCUS[Math.floor(i / 7)] || WEEK_FOCUS[WEEK_FOCUS.length - 1],
    tip: DAY_TIPS[i] || null,
    milestone: MILESTONES[n] || null,
    lastPatchISO: addDaysISO(QUIT, TOTAL_DAYS - 1),
  };
}

// אינדקס יציב לסבב תוכן יומי (לא תלוי אזור זמן)
export const dayIndex = iso => Math.floor(toUTC(iso) / 86400000);
export const pick = (arr, iso, offset = 0) => arr[(dayIndex(iso) + offset + arr.length * 10) % arr.length];
