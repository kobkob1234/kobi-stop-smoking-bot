// ---------- אחזור ----------
const norm = s => String(s)
  .replace(/[״"׳'`.,!?;:()\[\]{}־–—]/g, ' ')
  .replace(/\s+/g, ' ')
  .trim();

// עברית: "הקפה" צריך להתאים ל"קפה", "במדבקה" ל"מדבקה" וכו׳.
// מחזיר את כל הצורות הסבירות של מילה — עם ובלי אותיות שימוש, ועם ובלי ו׳ החיבור.
function forms(w) {
  const P = 'הובלכמש';                      // אותיות שימוש
  const out = new Set([w]);
  if (w.length >= 4 && P.includes(w[0])) out.add(w.slice(1));           // הקפה → קפה
  if (w.length >= 5 && P.includes(w[0]) && P.includes(w[1])) out.add(w.slice(2)); // כשמשעמם → משעמם
  return [...out];
}

/**
 * מחזיר את הרשומות הרלוונטיות, מדורגות. score גבוה = התאמה טובה יותר.
 * ההיגיון: התאמת ביטוי שלם שווה יותר מהתאמת מילה בודדת, ומילים ארוכות
 * שוות יותר מקצרות (כדי ש"לחץ" לא יתפוס כל דבר).
 */
export function search(query, limit = 3) {
  const q = ' ' + norm(query) + ' ';
  const words = q.split(' ').filter(w => w.length >= 3).flatMap(forms);
  const out = [];

  for (const e of KB) {
    let score = 0;
    for (const key of e.k) {
      const nk = norm(key);
      if (nk.includes(' ')) {
        // ביטוי שלם — התאמה חזקה
        if (q.includes(nk)) { score += 6 + nk.length / 4; continue; }
        // או: כל מילות הביטוי מופיעות, גם אם לא ברצף
        const kw = nk.split(' ').filter(x => x.length >= 3);
        if (kw.length > 1 && kw.every(x => words.some(w => w === x || (w.length >= 4 && (w.startsWith(x) || x.startsWith(w)))))) {
          score += 5;
        }
      } else {
        for (const w of words) {
          if (w === nk) { score += 4; break; }
          if (w.length >= 4 && (w.startsWith(nk) || nk.startsWith(w))) { score += 2; break; }
        }
      }
    }
    if (score > 0) out.push({ ...e, score });
  }
  return out.sort((a, b) => b.score - a.score).slice(0, limit);
}

/** תשובה ישירה כשההתאמה בטוחה מספיק */
export function answer(query) {
  const hits = search(query, 2);
  if (!hits.length || hits[0].score < 4) return null;
  const top = hits[0];
  const alt = hits[1] && hits[1].score >= top.score * 0.6 ? hits[1] : null;
  return {
    text: `<b>${top.t}</b>\n\n${top.a}\n\n<code>— ${top.src}</code>`,
    t: top.t,
    also: alt ? alt.t : null,
    id: top.id,
    score: top.score,
  };
}

/** הקשר ל-AI: הקטעים הרלוונטיים ביותר, כטקסט */
export function context(query, limit = 3) {
  return search(query, limit)
    .map(e => `### ${e.t}  (מקור: ${e.src})\n${e.a.replace(/<\/?b>/g, '').replace(/<\/?i>/g, '')}`)
    .join('\n\n');
}
