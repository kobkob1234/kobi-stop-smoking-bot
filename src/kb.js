/** מזריק מושגים קשורים למילות השאילתה */
function expand(words, q) {
  const add = new Set();
  for (const [triggers, targets] of CONCEPTS) {
    if (triggers.some(t => t.includes(' ') ? q.includes(' ' + t + ' ') : words.includes(t)))
      targets.forEach(x => add.add(x));
  }
  return [...add];
}

