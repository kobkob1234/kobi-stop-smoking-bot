const norm = s => String(s)
  .replace(/[״"׳'`.,!?;:()\[\]{}־–—]/g, ' ')
  .replace(/\s+/g, ' ')
  .trim();

// עברית: "הקפה" צריך להתאים ל"קפה", "במדבקה" ל"מדבקה" וכו׳.
// מחזיר את כל הצורות הסבירות של מילה — עם ובלי אותיות שימוש, ועם ובלי ו׳ החיבור.
function forms(w) {
  const P = 'הובלכמש';                      // אותיות שימוש
  const out = new Set([w]);
  if (w.length >= 4 && P.includes(w[0])) out.add(w.slice(1));           // הקפה → קפה
  if (w.length >= 5 && P.includes(w[0]) && P.includes(w[1])) out.add(w.slice(2)); // כשמשעמם → משעמם
  return [...out];
}


