/** הערכים שחולצו בסשן — שורדים את חיתוך ההיסטוריה */
export function capturedChain(turns = []) {
  const vals = turns.map(t => t.captured).filter(Boolean);
  return vals.length ? `נאמר עד כה בסשן: ${vals.join(' · ')}` : '';
}

