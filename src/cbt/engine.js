/**
 * תור אחד. `call(role, prompt)` מוזרק — כך המנוע נבדק בלי רשת ובלי מפתח.
 *
 * מחזיר גם `trace` עם כל הצעדים, כי סשן שאי אפשר לבדוק מה קרה בו אינו
 * שונה מקופסה שחורה — וזו בדיוק הבעיה שהפרוטוקול נועד לפתור.
 */
export async function runTurn({ tool, state, userText, call, retrieve = null,
                                turns = [], opening = [], formulation = null }) {
  const trace = [];
  const step = async (role, prompt) => {
    const out = await call(role, prompt, role === 'respond' ? THERAPIST_SYSTEM : undefined);
    trace.push({ role, ok: !!out, chars: (out || '').length });
    return out;
  };

  // כלי הצהרתי — אין למה להגיב, ואין טעם לשרוף קריאה
  if (tool.mode === 'fixed' || tool.mode === 'scale') {
    return { text: tool.run(state).text, trace, mode: tool.mode };
  }

  // **פלט מובנה ולא התאמת מחרוזת.** הגרסה הראשונה בדקה
  // `/חשיפה|מצוקה|סכנה/` על טקסט חופשי — כלומר "he is in crisis"
  // באנגלית, או "הוא בשבר", היו חומקים. ל-triage שמופקד על בטיחות
  // אסור להיות עם false negative, ולכן הקטגוריה נדרשת מפורשות
  // ו**כל דבר שאינו קטגוריה מוכרת נחשב חשיפה** — נטייה לצד הבטוח.
  const triage = await step('triage', [
    `המשתמש ענה: "${userText}"`,
    '',
    'סווג לקטגוריה אחת בלבד, והחזר את המילה באנגלית ותו לא:',
    '· answer    — ענה לשאלה',
    '· evasion   — התחמק, שינה נושא, או ענה בכלליות',
    '· pushback  — חולק, מתנגד, או מבטל את הרלוונטיות',
    '· distress  — סכנה לעצמו, ייאוש עמוק, או בקשת עזרה מעבר לגמילה',
    '',
    // ═══ הקטגוריה הזו סיווגה "היה לי דחף חזק אתמול בלילה" כמצוקה ═══
    //
    // כלומר הכלי שכל תפקידו לדבר על דחפים עצר ברגע שנאמר "דחף".
    // מערכת שנעצרת כשמזכירים את מה שהיא קיימת בשבילו אינה בטוחה
    // יותר — היא מלמדת לא להזכיר.
    'דחף, מעידה, שבוע קשה, עצבנות, "לא יודע מה לעשות" — כל אלה הם',
    '**החומר של הסשן**, לא מצוקה. סווג אותם answer.',
    'distress שמור למשפטים כמו "אין טעם", "אני לא רוצה להיות פה",',
    '"אני לא מסוגל יותר" — כאב שאינו על העישון.',
  ].join('\n'));

  const kind = classifyTriage(triage);
  // חשיפה מדאיגה עוצרת את הפרוטוקול. הצ׳קליסט אינו חשוב מזה.
  if (kind === 'distress') {
    return { text: null, halt: true, reason: triage, trace, mode: 'halt' };
  }

  // חילוץ הערך שיישמר. רץ רק כשיש מה לשמור — כלי הצהרתי לא מגיע לכאן.
  let captured = null;
  if (['free', 'if-then', 'homework', 'scale-0-10'].includes(tool.run(state).expects)) {
    const raw = await step('extract',
      `שאלה: "${tool.run(state).ask}"\nתשובה: "${userText}"\n\n` +
      'החזר את הערך המהותי בלבד, עד 6 מילים, בלי מילות מילוי ובלי "אני חושב ש". ' +
      'אם אין ערך ברור — החזר NONE.');
    captured = raw && !/^NONE\b/i.test(raw.trim()) ? raw.trim().slice(0, 80) : null;
  }

  // האחזור. **מונחים באנגלית במפורש** — הספרייה באנגלית, והשיחה
  // בעברית, ולכן בקשה ל"נושאים" הייתה מחזירה מונחים שלא נפגשים עם
  // שום מקטע. הדירוג היה נשען אז על תג ה-BCT בלבד, בלי שאיש יבחין.
  let sources = [];
  if (retrieve) {
    const want = await step('fetch',
      `הכלי: ${tool.name} (${tool.id}). המשתמש אמר: "${userText}"\n${FETCH_ASK}`);
    sources = await retrieve(want || tool.id);
  }

  // **השאלה שנשאלה** חייבת להיות בפרומפט. בלעדיה המודל רואה תשובה
  // ולא יודע על מה — "לא בא לי" יכול להיות על הטעם, על השעה, או על
  // הכול. הגרסה הראשונה השמיטה את זה, וזה היה הליקוי החמור ביותר.
  const asked = tool.run(state);
  const hist = historyDigest(turns);
  const draft = await step('respond', [
    `כלי נוכחי: ${tool.name} · ${tool.evidence}`,
    `שאלת אותו: "${asked.ask || asked.text}"`,
    `הוא ענה: "${userText}"`,
    '',
    `הנתונים שלו: ${stateDigest(state)}`,
    // הדפוס שזוהה עד עכשיו. היה נבנה ולא נשלח — כלומר הפורמולציה
    // הייתה תרגיל שאיש לא קרא את תוצאתו.
    formulation ? `הדפוס שזוהה עד עכשיו: "${formulation}"` : '',
    // הערכים שכבר חולצו בסשן הזה. זולים (6 מילים כל אחד) ושורדים את
    // חיתוך ההיסטוריה — כך תור 7 עדיין רואה מה נאמר בתור 1.
    capturedChain(turns),
    opening.length ? `מהסשן הקודם: ${opening.map(describeOpening).filter(Boolean).join(' · ')}` : '',
    hist ? `קודם בסשן הזה:\n${hist}` : '',
    sources.length
      ? `רקע מקצועי (לביסוס הניסוח שלך — אל תצטט ממנו יותר ממשפט):\n${
          sources.map(s => `[${s.src || 'מקור'}] ${s.text}`).join('\n---\n')}`
      : '',
    '',
    'כללים:', ...RESPOND_RULES.map(r => `· ${r}`),
    '', 'דוגמאות:', exemplarText(tool.id),
  ].filter(Boolean).join('\n'));

  if (!draft) return { text: null, captured, trace, mode: 'failed' };

  // הביקורת חייבת לראות את **אותו הקשר** כמו הכותב. הגרסה הראשונה
  // ראתה רק את הטיוטה ואת דברי המשתמש, ולכן לא יכלה לשפוט את הכלל
  // "חבר בין מה שאמר לנתונים" — הנתונים לא היו מולה.
  const critiquePrompt = (candidate) => [
    `שאלת אותו: "${asked.ask || asked.text}"`,
    `הוא ענה: "${userText}"`,
    `הנתונים שלו: ${stateDigest(state)}`,
    formulation ? `הדפוס שזוהה: "${formulation}"` : '',
    '', `התשובה שנכתבה: "${candidate}"`, '',
    ...CRITIQUE_RULES.map(r => `· ${r}`),
    '',
    // ═══ חוזה פלט, לא "החזר גרסה מתוקנת" ═══
    //
    // הניסוח הקודם הרשה כל מחרוזת, והקוד לקח כל דבר שאינו "OK" כתשובת
    // המטפל. מודל שענה על הכללים בפרוזה — "התשובה גנרית, היא לא
    // מתייחסת למה שהוא אמר" — שלח את הביקורת **כלשונה** לאדם בגמילה.
    'החזר בדיוק אחת משתי הצורות:',
    '  OK',
    '  FIX: <התשובה המתוקנת, כפי שתישלח אליו>',
    'בלי הסבר, בלי ניתוח, ובלי לדבר על התשובה בגוף שלישי.',
  ].join('\n');

  const keep = (t) => ({ text: t, revised: false, verified: true,
                         captured, kind, sources, trace, mode: 'responsive' });

  const first = readCritique(draft, await step('critique', critiquePrompt(draft)));
  if (first.ok || !first.fix) return keep(draft);

  // ═══ הסיבוב השני באמת מכריע ═══
  //
  // הגרסה הקודמת החזירה `text: first` בין אם הסיבוב השני אישר ובין אם
  // לא, ורק חישבה `verified` — ש-`session.js` לא העביר הלאה. כלומר
  // קריאת מודל שלמה נשרפה על דגל שאיש לא קרא, והתיקון נלקח בעיוורון
  // בדיוק כפי שההערה טענה שאינו.
  const second = readCritique(first.fix, await step('critique', critiquePrompt(first.fix)));
  if (second.ok) return { ...keep(first.fix), revised: true };
  // הסיבוב השני הציע תיקון משלו — הוא ראה גם את הטיוטה וגם את התיקון,
  // ולכן הוא ההצעה המעודכנת ביותר. אם גם הוא פסול, חוזרים לטיוטה:
  // הטיוטה לפחות נכתבה כתשובה.
  if (second.fix) return { ...keep(second.fix), revised: true, verified: false };
  return { ...keep(draft), verified: false };
}

/**
 * פענוח תשובת הביקורת לפי החוזה `OK` / `FIX: <טקסט>`.
 *
 * **כל דבר אחר נדחה.** הקוד הקודם בדק רק `/^OK\b/i` ולקח כל מחרוזת
 * אחרת כתשובת המטפל — כולל ביקורת בפרוזה.
 *
 * שתי בדיקות שפיות מעבר לחוזה, כי מודל לא תמיד מציית לפורמט:
 *   · אורך — תשובת מטפל היא עד שלושה משפטים ושאלה, לא פסקה.
 *   · מטא-שפה — "התשובה", "גנרית", "היא לא מתייחסת" הן דיבור **על**
 *     התשובה, לא התשובה.
 */
const META_TALK = /\b(התשובה|התגובה|הניסוח)\b|גנרי|מתייחסת|עוברת את|יש לתקן|הכלל ה/;

export function readCritique(candidate, raw) {
  const t = String(raw ?? '').trim();
  if (!t) return { ok: false, fix: null };            // כשל מודל — משאירים טיוטה
  if (/^OK\b/i.test(t)) return { ok: true, fix: null };
  const m = t.match(/^FIX:\s*([\s\S]+)$/i);
  const fix = (m ? m[1] : t).trim();
  if (!fix || fix === candidate) return { ok: true, fix: null };
  if (fix.length > CRITIQUE_MAX_CHARS) return { ok: false, fix: null };
  if (META_TALK.test(fix)) return { ok: false, fix: null };
  return { ok: false, fix };
}

/** תשובת מטפל היא עד שלושה משפטים ושאלה. מעבר לזה — לא תשובה. */
export const CRITIQUE_MAX_CHARS = 600;

/**
 * סיווג בטוח-בברירת-מחדל.
 *
 * מוכר → הקטגוריה. **לא מוכר, ריק, או כשל מודל → distress**, כי
 * הכיוון היקר הוא לפספס מצוקה, לא לעצור סשן מיותר.
 */
/**
 * סיווג ה-triage.
 *
 * **נטייה לצד הבטוח — אבל רק על תשובה שהתקבלה.** תשובה שאינה קטגוריה
 * מוכרת נחשבת מצוקה, כי false negative כאן יקר. אבל **היעדר תשובה
 * אינו סיגנל קליני**: הוא אומר שהרשת נפלה או שהמכסה נגמרה, ולהציג
 * טלפוני חירום למי שהחיבור שלו נותק זה גם שגוי וגם מפחיד.
 *
 * מחזיר `null` על כלום — והמתקשר ממשיך בלי שער ה-triage.
 */
export function classifyTriage(raw) {
  const s = String(raw ?? '').trim().toLowerCase();
  if (!s) return null;
  for (const k of ['distress', 'evasion', 'pushback', 'answer']) {
    if (s.includes(k)) return k;
  }
  return 'distress';
}

/** openingContext → משפט קצר. בלי זה הרצף משלב 4 נבנה ולא בשימוש. */
export function describeOpening(b) {
  switch (b.kind) {
    case 'homework':   return `שיעורי בית פתוחים מלפני ${b.daysAgo} ימים: "${b.text}"`;
    case 'confidence': return `הביטחון ${b.from > b.to ? 'ירד' : 'עלה'} ${b.from}→${b.to}`;
    case 'last':       return `הסשן הקודם היה לפני ${b.daysAgo} ימים`;
    default:           return null;
  }
}

/** כמה קריאות תור אחד עולה — לתקצוב מול המכסה */
export const turnCost = (toolMode, withRetrieval = true) =>
  toolMode === 'fixed' || toolMode === 'scale' ? 0 : (withRetrieval ? 4 : 3);

// ==========================================================================
//  פורמולציה — מה שמטפל עושה ורשימת כלים לא
//
//  כל תור עומד בפני עצמו. מה שאף כלי אינו עושה הוא **לחבר**: שהוא אמר
//  "עייף" בשלושה סשנים, שהביטחון יורד בזמן שהימים הנקיים עולים, שהמסטיק
//  נופל דווקא בערב שהוא עצמו סימן.
//
//  זה רץ פעם אחת בסוף הסשן, על הכול, ונשמר. הסשן הבא נפתח ממנו — ולכן
//  זה גם מה שהופך רצף מנתונים לתובנה.
// ==========================================================================
export async function formulate({ state, turns, priorFormulation, call }) {
  if (!turns.length) return null;
  const out = await call('formulate', [
    'להלן סשן CBT שהסתיים. נסח **דפוס אחד** — לא סיכום.',
    '',
    `נתונים: ${stateDigest(state)}`,
    priorFormulation ? `הדפוס שזוהה קודם: "${priorFormulation}"` : '',
    '',
    'מה נאמר בסשן:',
    ...turns.map(t => `· ${t.tool}: "${String(t.answer).slice(0, 160)}"`),
    '',
    'כתוב משפט אחד או שניים שמחברים בין דברים שנאמרו לבין הנתונים.',
    'אם הדפוס הקודם עדיין מחזיק — חזק אותו. אם השתנה — אמור מה השתנה.',
    'אם אין מספיק כדי לזהות דפוס — החזר NONE. עדיף כלום מדפוס מומצא.',
  ].filter(Boolean).join('\n'));
  if (!out || /^NONE\b/i.test(out.trim())) return null;
  return out.trim().slice(0, 400);
}
