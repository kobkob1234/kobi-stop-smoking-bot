// ==========================================================================
//  partner.js — הנתיב היחיד שנוגע באדם שלישי
//
//  כל שאר הבוט מדבר עם משתמש אחד ופועל על נתונים שלו. כאן, ורק כאן,
//  יוצאת הודעה **לבת הזוג** — ולכן זה הקוד היחיד שטעות בו אינה הפיכה.
//  אי אפשר לבטל התראה שנשלחה, ואי אפשר לפצות על התראה שלא נשלחה.
//
//  ההערות למטה מתעדות שני באגים אמיתיים שכבר היו בקוד הזה:
//    • סימון reported=true בלי ששום דבר נשלח — הנתונים וההודעה למשתמש
//      אמרו "דווח" כשלא דווח.
//    • מגרה שחסמה גם "כלפי מטה", כך שדיווח דרגה 3 (בדרך לקנות) נחסם
//      על ידי דיווח דרגה 2 שקדם לו.
//  שניהם תוקנו — וישבו כאן בלי אף בדיקה, כי הקוד היה קבור ב-index.js
//  ולא היה מיוצא. החילוץ הזה הוא מה שמאפשר לנעול אותם.
// ==========================================================================
import { send } from './telegram.js';
import * as C from './content.js';

/** מגרה בין התראות מאותה דרגה בדיוק. שניות, לא דקות — ראה למטה. */
export const SAME_LEVEL_DEBOUNCE_MS = 90 * 1000;

/** שולח לשותף/ה. מחזיר true אם נמסר. */
export async function notifyPartner(env, meta, text) {
  if (!meta.partnerChatId || meta.partnerMute || meta._dryRun) return false;
  const r = await send(env, meta.partnerChatId, text);
  if (!r.ok) console.log('דיווח לשותף/ה נכשל:', r.description);
  return !!r.ok;
}

/**
 * מדווח לשותפה — **רק בדרגות החמורות** (2 ו-3).
 *
 * דחף רגיל לא מגיע אליה: הוא חלק מהיום, והיא לא צריכה להיות צד לכל
 * אחד מהם. מה שכן מגיע: מחשבות שמייצרות תירוצים לצאת, ובדרך לקנות.
 *
 * מגרה: דיווח מאותה דרגה לא חוזר תוך 90 שניות, אבל **הסלמה לדרגה
 * גבוהה יותר עוברת תמיד** — זה בדיוק מה שהיא צריכה לדעת.
 *
 * למה 90 שניות ולא 30 דקות: בדרגות האלה עדיף שתקבל פעמיים מאשר שלא
 * תקבל. המגרה מגנה רק מפני לחיצה כפולה בטעות, ואין להאריך אותה.
 */
export async function alertPartner(env, meta, level, dry = false) {
  if (level < 2) return false;
  // בדיקות שלי שלחו לה התראות דחופות אמיתיות. dry מאפשר לאמת את
  // הזרימה בלי להפעיל אותה על אדם שלישי.
  if (dry) { console.log('PARTNER דרגה', level, '— dry, לא נשלח'); return false; }
  if (!meta.partnerChatId || meta.partnerMute || meta._dryRun) return false;

  const sameLevel = (meta.lastPartnerAlertLevel || 0) === level;
  if (sameLevel && Date.now() - (meta.lastPartnerAlert || 0) < SAME_LEVEL_DEBOUNCE_MS) return true;

  const body = level >= 3
    ? [`🆘 <b>${C.PARTNER_MSG_ENROUTE}</b>`, '',
       '<i>זו הדרגה הדחופה — הוא בדרך לקנות ולחץ על הכפתור במקום להמשיך.</i>',
       '<b>אם אפשר: תתקשרי אליו עכשיו.</b> שיחה אחת מפרקת את הסודיות שהסבבים חיו עליה.',
       '<i>ולעולם לא להציע "אז קח שאכטה".</i>']
    : [`🧠 <b>${C.PARTNER_MSG_PLANNING}</b>`, '',
       '<i>לא סתם דחף — מחשבות שמייצרות תירוצים לצאת. זו התחנה הראשונה בשרשרת.</i>',
       '<b>מה שעוזר: אם הוא יוצא — לצאת איתו.</b> זה המצב שהתוכנית מייעדת לך.',
       '<i>זה דיווח ולא בקשת רשות. ולעולם לא להציע "אז קח שאכטה".</i>'];

  const ok = await notifyPartner(env, meta, body.join('\n'));
  console.log('PARTNER דרגה', level, ok ? 'נשלח ✓' : 'נכשל ✗');
  // כישלון שליחה **אינו** מעדכן את החותמת. אחרת ניסיון שנכשל היה
  // פותח מגרה של 90 שניות ומונע את הניסיון הבא — כלומר הכשל היה
  // מנציח את עצמו בדיוק ברגע הכי גרוע.
  if (!ok) return false;
  meta.lastPartnerAlert = Date.now();
  meta.lastPartnerAlertLevel = level;
  return true;
}
